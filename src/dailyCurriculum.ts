export const dailyCurriculum: CurriculumLesson[] = packs.flatMap(pack =>
  pack.titles.map((title, index) => ({
    id: `curriculum-${pack.grade}-${pack.subject}-${index + 1}`,
    grade: pack.grade,
    subject: pack.subject,
    week: Math.floor(index / 2) + 1,
    lessonInWeek: (index % 2 === 0 ? 1 : 2) as 1 | 2,
    title,
    source: pack.source,
    summary: pack.summaries?.[index] || `الدرس ${index + 1} من منهج ${pack.subject} لل${pack.grade}، مستند إلى ${pack.source}.`,
  }))
);

export function getCurriculumLessons(grade?: string, subject?: string) {
  return dailyCurriculum.filter(item =>
    (!grade || item.grade === grade) && (!subject || item.subject === subject)
  );
}
